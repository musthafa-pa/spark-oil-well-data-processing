SPPA (Stand Pipe Pressure Average): This is the average pressure measured at the standpipe, which is a critical point in the drilling fluid circulation system. It's important for monitoring the pressure being applied to the drill bit and ensuring that it remains within safe operational limits to avoid issues like a blowout.

ROP30s (Rate of Penetration over 30 seconds): This represents the rate at which the drill bit is advancing through the formation, averaged over a 30-second interval. It's typically measured in feet per hour or meters per hour. A higher ROP indicates faster drilling, but it must be balanced with other parameters to prevent excessive wear on the drill bit or equipment.

TQ30s (Torque over 30 seconds): This measures the rotational force applied to the drill string, averaged over a 30-second interval. Torque is a critical parameter that indicates how much resistance the drill bit encounters while drilling. High torque values can indicate issues such as bit wear, sticky formations, or equipment problems.

ECD_MW_IN (Equivalent Circulating Density in Mud Weight Input): This is a measure of the effective density of the drilling fluid, taking into account the additional pressure exerted by fluid circulation. ECD is crucial for maintaining wellbore stability and avoiding issues like fracturing the formation or causing a wellbore collapse. It's typically expressed in pounds per gallon (ppg) or kilograms per liter (kg/L).

